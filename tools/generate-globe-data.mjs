// Regenerates ../assets/js/globe-data.js — the dotted land points used by the globe.
//
// Usage (from this folder):
//   npm init -y && npm i world-atlas@2 topojson-client@3 d3-geo@3
//   node generate-globe-data.mjs
//
// Encoding: each point is 6 base-36 characters.
//   chars 0-2 = latitude  * 10 + 900
//   chars 3-5 = longitude * 10 + 1800

import fs from 'fs';
import { createRequire } from 'module';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-110m.json');
const land = feature(topo, topo.objects.land);

const STEP = 2.0;            // degrees between dots (smaller = denser globe)
const out = [];
for (let lat = -58; lat <= 78; lat += STEP) {
  const n = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)));
  for (let i = 0; i < n; i++) {
    const lon = -180 + ((i + 0.5) * 360) / n;
    if (geoContains(land, [lon, lat])) out.push([Math.round(lat * 10), Math.round(lon * 10)]);
  }
}

const enc = out
  .map(([a, b]) => (a + 900).toString(36).padStart(3, '0') + (b + 1800).toString(36).padStart(3, '0'))
  .join('');

const header = `/* Dotted world map for the globe.
   Each point = 6 base-36 chars: 3 for latitude, 3 for longitude (value/10 - 90 | -180).
   Generated by tools/generate-globe-data.mjs — do not edit by hand. */\n`;

fs.writeFileSync(new URL('../assets/js/globe-data.js', import.meta.url), `${header}window.GLOBE_LAND = "${enc}";\n`);
console.log(`${out.length} points written`);
